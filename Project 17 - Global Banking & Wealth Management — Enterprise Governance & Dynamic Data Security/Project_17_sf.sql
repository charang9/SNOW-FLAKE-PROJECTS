CREATE OR REPLACE SECURE VIEW SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY
AS
SELECT REGION,
       SUM(amount) TOTAL_SETTLED_VAL,
       count(*) SETTLED_TXN_COUNT,
       ROUND(avg(amount),2) AVG_SETTLED_AMOUNT
from silver_bank_transactions
where status = 'SETTLED'
GROUP BY REGION;

SELECT * FROM SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY;

SELECT
    B.BRONZE_GROSS_TOTAL,
    S.SILVER_GROSS_TOTAL,
    G.GOLD_GROSS_TOTAL,
    (B.BRONZE_GROSS_TOTAL = S.SILVER_GROSS_TOTAL) AS RECONCILED_FLAG
FROM
(
    SELECT SUM(PAYLOAD:amount::NUMBER(15,2)) AS BRONZE_GROSS_TOTAL
    FROM BRONZE_BANK_PAYLOADS
) B
CROSS JOIN
(
    SELECT SUM(AMOUNT) AS SILVER_GROSS_TOTAL
    FROM SILVER_BANK_TRANSACTIONS
) S
CROSS JOIN
(
    SELECT SUM(TOTAL_SETTLED_VAL) AS GOLD_GROSS_TOTAL
    FROM SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY
) G;












       
