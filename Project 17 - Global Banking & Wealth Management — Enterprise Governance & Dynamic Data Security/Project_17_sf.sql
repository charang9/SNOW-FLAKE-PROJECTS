/*  4 ROW ACCESS POLICY */


CREATE OR REPLACE ROW ACCESS POLICY RAP_REGION_POLICY
AS (REGION STRING)
RETURNS BOOLEAN ->
CASE
    WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN','COMPLIANCE_OFFICER') THEN TRUE
    WHEN CURRENT_ROLE() = 'NA_ANALYST' AND REGION = 'NA' THEN TRUE
    WHEN CURRENT_ROLE() = 'EU_ANALYST' AND REGION = 'EU' THEN TRUE
    ELSE FALSE
END;

ALTER TABLE SILVER_BANK_TRANSACTIONS
ADD ROW ACCESS POLICY RAP_REGION_POLICY
ON (REGION);



