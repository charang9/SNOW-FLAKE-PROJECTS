/* TASK 3  Dynamic Data Masking (DDM)  */ 

CREATE OR REPLACE MASKING POLICY MASK_SSN
AS (CLIENT_SSN STRING)
RETURNS STRING ->
CASE
    WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN', 'COMPLIANCE_OFFICER')
    THEN CLIENT_SSN
    ELSE CONCAT('***-**-', RIGHT(CLIENT_SSN, 4))
END;

ALTER TABLE SILVER_BANK_TRANSACTIONS
MODIFY COLUMN CLIENT_SSN
SET MASKING POLICY MASK_SSN;

USE ROLE NA_ANALYST;
SELECT TXN_ID, CLIENT_SSN,ACCOUNT_NO
FROM SILVER_BANK_TRANSACTIONS;


CREATE OR REPLACE MASKING POLICY MASK_ACCOUNT
AS (ACCOUNT_NO STRING)
RETURNS STRING ->
CASE
