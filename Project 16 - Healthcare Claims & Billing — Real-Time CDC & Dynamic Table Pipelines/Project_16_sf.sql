/* creating silver */

CREATE OR REPLACE TABLE SILVER_CLAIMS_TRANSACTIONS
(
    CLAIM_ID STRING,
    SUBMITTED_AT TIMESTAMP,
    PATIENT_ID NUMBER,
    PROVIDER_ID STRING,
    DIAGNOSIS_CODE STRING,
    BILLED_AMOUNT NUMBER(12,2),
    COPAY_AMOUNT NUMBER(12,2),
    NET_PAYABLE_AMOUNT NUMBER(12,2),
    STATUS STRING
);

SELECT * FROM SILVER_CLAIMS_TRANSACTIONS;

/* MERGING INTO SILVER USING STREAM */

MERGE INTO SILVER_CLAIMS_TRANSACTIONS s
USING stream_bronze_claims st
ON s.claim_id = st.PAYLOAD:claim_id::STRING

WHEN MATCHED THEN
UPDATE
SET
    PATIENT_ID = st.PAYLOAD:patient_id::NUMBER,
    SUBMITTED_AT = st.PAYLOAD:submitted_at::TIMESTAMP,
    PROVIDER_ID = st.PAYLOAD:provider_id::STRING,
    DIAGNOSIS_CODE = st.PAYLOAD:diagnosis_code::STRING,
    BILLED_AMOUNT = st.PAYLOAD:billed_amount::NUMBER(12,2),
    COPAY_AMOUNT = st.PAYLOAD:copay_amount::NUMBER(12,2),
    NET_PAYABLE_AMOUNT =
        st.PAYLOAD:billed_amount::NUMBER(12,2)
        - st.PAYLOAD:copay_amount::NUMBER(12,2),
    STATUS = st.PAYLOAD:status::STRING

WHEN NOT MATCHED THEN

INSERT
(
    CLAIM_ID,
    SUBMITTED_AT,
    PATIENT_ID,
    PROVIDER_ID,
    DIAGNOSIS_CODE,
    BILLED_AMOUNT,
    COPAY_AMOUNT,
    NET_PAYABLE_AMOUNT,
    STATUS
)
values(
    st.PAYLOAD:claim_id::STRING,
    st.PAYLOAD:submitted_at::TIMESTAMP,
    st.PAYLOAD:patient_id::NUMBER,
    st.PAYLOAD:provider_id::STRING,
    st.PAYLOAD:diagnosis_code::STRING,
    st.PAYLOAD:billed_amount::NUMBER(12,2),
    st.PAYLOAD:copay_amount::NUMBER(12,2),
    st.PAYLOAD:billed_amount::NUMBER(12,2) -
        st.PAYLOAD:copay_amount::NUMBER(12,2),
    st.PAYLOAD:status::STRING
);

CREATE OR REPLACE DYNAMIC TABLE DT_PROVIDER_FINANCIAL_SUMMARY
TARGET_LAG = '1 MINUTE'
WAREHOUSE = WH_16
AS 
SELECT PROVIDER_ID,
       sum(billed_amount) AS TOTAL_BILLED_AMOUNT,
       sum(COPAY_AMOUNT) AS TOTAL_COPAY_COLLECT,
       sum(net_payable_amount) AS TOTAL_NET_PAYABLE,
       count(*) AS APPROVED_CLAIMS
FROM SILVER_CLAIMS_TRANSACTIONS
where status = 'APPROVED'
group by PROVIDER_ID;

