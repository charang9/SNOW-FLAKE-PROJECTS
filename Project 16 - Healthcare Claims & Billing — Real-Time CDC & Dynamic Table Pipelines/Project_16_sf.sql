SELECT
    b.BRONZE_GROSS_TOTAL,
    s.SILVER_GROSS_TOTAL,
    g.GOLD_GROSS_TOTAL,
    (s.SILVER_GROSS_TOTAL = 197700
     AND g.GOLD_GROSS_TOTAL = 152700) AS RECONCILED_FLAG
FROM
(
    SELECT SUM(PAYLOAD:billed_amount::NUMBER(12,2)) AS BRONZE_GROSS_TOTAL
    FROM BRONZE_RAW_CLAIMS /* all 8 rows sum */
) b
CROSS JOIN
(
    SELECT SUM(BILLED_AMOUNT) AS SILVER_GROSS_TOTAL
    FROM SILVER_CLAIMS_TRANSACTIONS /* non duplicate sum */
) s
CROSS JOIN
(
    SELECT SUM(TOTAL_BILLED_AMOUNT) AS GOLD_GROSS_TOTAL
    FROM DT_PROVIDER_FINANCIAL_SUMMARY /* only approved sum */
) g;







